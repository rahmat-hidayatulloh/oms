package com.oms.config;

import io.micrometer.observation.ObservationRegistry;
import io.micrometer.observation.aop.ObservedAspect;
import io.opentelemetry.api.OpenTelemetry;
import io.opentelemetry.api.common.Attributes;
import io.opentelemetry.exporter.zipkin.ZipkinSpanExporter;
import io.opentelemetry.sdk.OpenTelemetrySdk;
import io.opentelemetry.sdk.resources.Resource;
import io.opentelemetry.sdk.trace.SdkTracerProvider;
import io.opentelemetry.sdk.trace.export.SimpleSpanProcessor;
import io.opentelemetry.sdk.trace.export.SpanExporter;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Configuration for Micrometer Tracing (OpenTelemetry bridge).
 *
 * <p>
 * Provides distributed tracing capability via Micrometer Tracing with OpenTelemetry
 * bridge and Zipkin exporter. When enabled, every request automatically generates:
 * <ul>
 *   <li>{@code traceId} — propagated across service boundaries</li>
 *   <li>{@code spanId} — individual operation identifier</li>
 * </ul>
 *
 * <p>
 * Trace IDs are automatically injected into SLF4J MDC under the key {@code traceId},
 * which is already used by {@link LoggingFilter} for request correlation.
 * When tracing is enabled, the {@code traceId} from Micrometer Tracing takes precedence
 * over the UUID-based traceId generated by {@link LoggingFilter}.
 *
 * <p>
 * Tracing is enabled via {@code management.tracing.enabled=true} in profile-specific configs
 * (staging, prod). It is disabled by default in dev.
 *
 * <p>
 * Zipkin exporter sends spans to the configured endpoint (default: http://localhost:9411/api/v2/spans).
 *
 * @see <a href="https://micrometer.io/docs/tracing">Micrometer Tracing Documentation</a>
 * @see <a href="https://opentelemetry.io/docs/languages/java/exporters/zipkin/">OpenTelemetry Zipkin Exporter</a>
 */
@Configuration
@ConditionalOnProperty(value = "management.tracing.enabled", havingValue = "true", matchIfMissing = false)
public class TracingConfig {

    private final String applicationName;
    private final String zipkinEndpoint;

    // V4-02: constructor injection instead of field-level @Value.
    public TracingConfig(
            @Value("${spring.application.name:oms}") String applicationName,
            @Value("${tracing.zipkin.endpoint:}") String zipkinEndpoint) {
        this.applicationName = applicationName;
        this.zipkinEndpoint = zipkinEndpoint;
    }

    /**
     * Creates the Zipkin span exporter that sends trace data to a Zipkin-compatible backend.
     */
    @Bean
    public SpanExporter zipkinSpanExporter() {
        return ZipkinSpanExporter.builder()
                .setEndpoint(zipkinEndpoint)
                .build();
    }

    /**
     * Configures OpenTelemetry SDK with the Zipkin exporter and service resource.
     */
    @Bean
    public OpenTelemetry openTelemetry(SpanExporter spanExporter) {
        // Set the service name as a resource attribute for span identification
        Resource resource = Resource.getDefault()
                .merge(Resource.create(Attributes.builder()
                        .put("service.name", applicationName)
                        .build()));

        SdkTracerProvider tracerProvider = SdkTracerProvider.builder()
                .addSpanProcessor(SimpleSpanProcessor.create(spanExporter))
                .setResource(resource)
                .build();

        return OpenTelemetrySdk.builder()
                .setTracerProvider(tracerProvider)
                .build();
    }

    /**
     * ObservationRegistry is auto-configured by Spring Boot when Micrometer Tracing
     * is on the classpath. This bean is provided for explicit injection if needed.
     */
    @Bean
    public ObservationRegistry observationRegistry() {
        return ObservationRegistry.create();
    }

    /**
     * Registers {@code @Observed} AOP support so that any bean method annotated
     * with {@link io.micrometer.observation.annotation.Observed} will automatically
     * create observation spans.
     */
    @Bean
    @ConditionalOnProperty(value = "management.tracing.observed-aspect", havingValue = "true", matchIfMissing = true)
    public ObservedAspect observedAspect(ObservationRegistry observationRegistry) {
        return new ObservedAspect(observationRegistry);
    }
}